import itertools, sys

def matchings(vs):
    if not vs:
        yield ()
        return
    a = vs[0]
    for i in range(1, len(vs)):
        b = vs[i]
        rest = vs[1:i] + vs[i+1:]
        for m in matchings(rest):
            yield ((a, b),) + m

def mate(m):
    d = {}
    for a, b in m:
        d[a] = b; d[b] = a
    return d

def ham(P, Q, N):
    p, q = mate(P), mate(Q)
    v, seen, use_p = 0, {0}, True
    while True:
        v = p[v] if use_p else q[v]
        use_p = not use_p
        if v == 0 and use_p:
            break
        seen.add(v)
    return len(seen) == N

def canon(m):
    return tuple(sorted(tuple(sorted(e)) for e in m))

def act(s, m):
    return canon(((s[a], s[b]) for a, b in m))

def gf2_rank_basis(rows):
    basis, piv = [], []
    for idx, r in enumerate(rows):
        x = r
        for b, p in zip(basis, piv):
            if (x >> p) & 1:
                x ^= b
        if x:
            p = x.bit_length() - 1
            for j in range(len(basis)):
                if (basis[j] >> p) & 1:
                    basis[j] ^= x
            basis.append(x); piv.append(p)
    return basis, piv

def coords(f, basis, piv):
    c = 0
    for j, (b, p) in enumerate(zip(basis, piv)):
        if (f >> p) & 1:
            c |= 1 << j
            f ^= b
    assert f == 0
    return c

def matmul(A, B, d):
    # A, B: list of column bitmasks (col j = image of basis vector j)
    out = []
    for j in range(d):
        col = B[j]; acc = 0; i = 0
        while col:
            if col & 1:
                acc ^= A[i]
            col >>= 1; i += 1
        out.append(acc)
    return out

def add(A, B):
    return [a ^ b for a, b in zip(A, B)]

def run(n):
    N = 2 * n
    M = [canon(m) for m in matchings(list(range(N)))]
    ix = {m: i for i, m in enumerate(M)}
    rows = []
    for P in M:
        r = 0
        for j, Q in enumerate(M):
            if ham(P, Q, N):
                r |= 1 << j
        rows.append(r)
    basis, piv = gf2_rank_basis(rows)
    d = len(basis)
    def op(s):
        cols = []
        for b in basis:
            # b is a row-space vector; act on functions: (s.f)(Q) = f(s^{-1} Q)
            sinv = [0] * N
            for i, si in enumerate(s):
                sinv[si] = i
            f = 0
            for j, Q in enumerate(M):
                if (b >> ix[act(sinv, Q)]) & 1:
                    f |= 1 << j
            cols.append(coords(f, basis, piv))
        return cols
    I = [1 << j for j in range(d)]
    Z = [0] * d
    def transp(i, j):
        s = list(range(N)); s[i], s[j] = s[j], s[i]; return s
    G = {}
    for i, j in itertools.combinations(range(N), 2):
        G[(i, j)] = op(transp(i, j))
    g = lambda i, j: G[(min(i, j), max(i, j))]
    ok = True
    edges = list(G)
    for e in edges:
        ok &= matmul(G[e], G[e], d) == I
    for e, f in itertools.product(edges, edges):
        anti = add(matmul(G[e], G[f], d), matmul(G[f], G[e], d))
        k = len(set(e) & set(f)) % 2
        ok &= anti == (I if k else Z)
    for i, j, k in itertools.combinations(range(N), 3):
        ok &= add(add(g(i, j), g(j, k)), g(i, k)) == Z
    # hyperbolic basis: E_k = sum_{i<=k} Gamma_{2i-1,2i}, F_k = Gamma_{2k,2k+1} (1-indexed)
    E, F = [], []
    acc = Z
    for k in range(1, n):
        acc = add(acc, g(2 * k - 2, 2 * k - 1))
        E.append(acc); F.append(g(2 * k - 1, 2 * k))
    hyp = True
    for k in range(n - 1):
        hyp &= matmul(E[k], E[k], d) == (I if (k + 1) % 2 else Z)
        hyp &= matmul(F[k], F[k], d) == I
        hyp &= add(matmul(E[k], F[k], d), matmul(F[k], E[k], d)) == I
        for l in range(n - 1):
            if l != k:
                for X in (E[k], F[k]):
                    for Y in (E[l], F[l]):
                        hyp &= matmul(X, Y, d) == matmul(Y, X, d)
    # algebra generated by E_k, F_k
    def flat(A):
        v = 0
        for j, c in enumerate(A):
            v |= c << (j * d)
        return v
    span_b, span_p = [], []
    def addvec(A):
        nonlocal span_b, span_p
        x = flat(A)
        for b, p in zip(span_b, span_p):
            if (x >> p) & 1:
                x ^= b
        if x:
            p = x.bit_length() - 1
            span_b.append(x); span_p.append(p)
            return True
        return False
    gens = E + F
    frontier = [I]; addvec(I); elems = [I]
    while frontier:
        new = []
        for A in frontier:
            for X in gens:
                B = matmul(X, A, d)
                if addvec(B):
                    new.append(B)
        frontier = new
    alg_dim = len(span_b)
    gam1 = Z
    for i in range(n):
        gam1 = add(gam1, g(2 * i, 2 * i + 1))
    gam1_ok = gam1 == (I if n % 2 else Z)
    print(f"n={n} |M|={len(M)} rank={d} 2^(n-1)={2**(n-1)} R1-R4={ok} "
          f"hyperbolic={hyp} dim<E,F>={alg_dim} d^2={d*d} Gamma(1)=(n mod 2)I:{gam1_ok}")

for n in map(int, sys.argv[1:]):
    run(n)
