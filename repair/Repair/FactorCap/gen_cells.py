"""Emit the 80 Farey cells of the P9 configuration as Lean data.

P9 is the factor-tail cap rho(T(n)) <= 5 at every prime n >= 17 (COD-186, results/cod-186-archive-cap-check.md).
Configuration a = (1,3,5,2,4,6,7,8), R = Q. The cells are the open intervals between consecutive Farey
fractions of order 16 in [0, 1]. For theta in a cell, entry i has floor k_i = floor(theta a_i), side
plus_i = [frac(theta a_i) < 1/2] and level ||theta a_i||. The entries sorted by level give the context
(exit end of each entry joined to the entry end of the next, cyclically). Z is the end set of the cycle
of Q u context through end 0, which is closed under both matchings and proper because the cycle count
is at least 2.

Ends: 2i is +a_i, 2i+1 is -a_i, as in scripts/cod-186-archive-cap-check.c.

Cross-checks (abort on any failure):
  1. the breakpoint set {k/(2a_i), k/|a_i-a_k|, k/(a_i+a_k)} equals the Farey sequence of order 16;
  2. every pair of Farey neighbours has determinant p'q - pq' = 1;
  3. the order string and the cycle count of every cell match cod-186-archive-cap-check-cells.out;
  4. the Lean checker's integer sign test passes on every cell (same arithmetic as Repair.FactorCap.Checker);
  5. for every prime n in [17, PRIME_MAX] and every mu in [1, n-1] the cell containing mu/n predicts
     mu a_i mod n exactly from (k_i, plus_i) and the level order.

Usage: python3 -I gen_cells.py CELLS_OUT OUT_LEAN [COUNT [OUT_CHECKS MODULE]]
  CELLS_OUT   path to cod-186-archive-cap-check-cells.out (organize-archive/scripts/)
  OUT_LEAN    Lean data file to write (module Repair.FactorCap.CellData)
  COUNT       number of cells to emit (default 80)
  OUT_CHECKS  optional Lean file with one `decide +kernel` theorem per emitted cell
  MODULE      the module name of OUT_CHECKS, used in its header (e.g. Repair.FactorCap.Cells)

The repo files are regenerated by
  python3 -I gen_cells.py CELLS_OUT CellData.lean 80 Cells.lean Repair.FactorCap.Cells
run from repair/Repair/FactorCap/.
"""
import re
import sys
from fractions import Fraction

A = [1, 3, 5, 2, 4, 6, 7, 8]
QX = [(-8, -7), (-6, -5), (-4, -3), (-2, -1), (1, 8), (2, 3), (4, 5), (6, 7)]
J = len(A)
PRIME_MAX = 400


def end_of(x):
    for i, a in enumerate(A):
        if a == x:
            return 2 * i
        if a == -x:
            return 2 * i + 1
    raise ValueError(x)


def q_pairs():
    return [tuple(sorted((end_of(x), end_of(y)))) for x, y in QX]


def farey(order):
    a, b, c, d = 0, 1, 1, order
    out = [(a, b)]
    while c <= order:
        k = (order + b) // d
        a, b, c, d = c, d, k * c - a, k * d - b
        out.append((a, b))
    return out


def breakpoints():
    dens = []
    for i in range(J):
        dens.append(2 * A[i])
        for k in range(i + 1, J):
            dens.append(abs(A[i] - A[k]))
            dens.append(A[i] + A[k])
    pts = set()
    for d in dens:
        for k in range(d + 1):
            pts.add(Fraction(k, d))
    return sorted(pts)


def entries_at(theta):
    ents = []
    for i, a in enumerate(A):
        y = theta * a
        k = y.numerator // y.denominator
        fr = y - k
        if fr == 0 or 2 * fr == 1:
            raise RuntimeError("breakpoint hit")
        plus = 2 * fr < 1
        lev = fr if plus else 1 - fr
        ents.append((lev, i, plus, k))
    ents.sort()
    for x, y in zip(ents, ents[1:]):
        if x[0] == y[0]:
            raise RuntimeError("level tie")
    return [(i, plus, k) for _, i, plus, k in ents]


def exit_end(e):
    i, plus, _ = e
    return 2 * i + 1 if plus else 2 * i


def entry_end(e):
    i, plus, _ = e
    return 2 * i if plus else 2 * i + 1


def ctx_pairs(order):
    return [(exit_end(e), entry_end(f)) for e, f in zip(order, order[1:] + order[:1])]


def components(pairs_a, pairs_b, n=2 * J):
    ma, mb = {}, {}
    for x, y in pairs_a:
        ma[x], ma[y] = y, x
    for x, y in pairs_b:
        mb[x], mb[y] = y, x
    seen, comps = set(), []
    for s in range(n):
        if s in seen:
            continue
        comp, v = [], s
        while True:
            comp.append(v)
            seen.add(v)
            w = ma[v]
            comp.append(w)
            seen.add(w)
            v = mb[w]
            if v == s:
                break
        comps.append(sorted(comp))
    return comps


def coef(e):
    i, plus, k = e
    return (A[i], k) if plus else (-A[i], -(k + 1))


def pos_on(cell, a, b):
    p, q, p2, q2 = cell
    x = a * p2 - b * q2
    y = a * p - b * q
    return x >= 0 and y >= 0 and x + y > 0


def lean_check(cell, order, z, qp):
    p, q, p2, q2 = cell
    if p2 * q != p * q2 + 1:
        return False
    if sorted(e[0] for e in order) != list(range(J)):
        return False
    for e in order:
        a, b = coef(e)
        if not pos_on(cell, a, b) or not pos_on(cell, -2 * a, -(2 * b + 1)):
            return False
    for e, f in zip(order, order[1:]):
        (a1, b1), (a2, b2) = coef(e), coef(f)
        if not pos_on(cell, a2 - a1, b2 - b1):
            return False
    zs = set(z)
    if not zs or len(zs) >= 2 * J or any(x >= 2 * J for x in z):
        return False
    for x, y in ctx_pairs(order) + qp:
        if (x in zs) != (y in zs):
            return False
    return True


def parse_cells_out(path):
    rows = []
    pat = re.compile(r"cell\s+(\d+) theta in \(([^,]+), ([^)]+)\)\s+order (.*?)\s+cycles\(Q u ctx\)=(\d+)")
    with open(path) as fh:
        for line in fh:
            m = pat.match(line)
            if m:
                rows.append((int(m.group(1)), Fraction(m.group(2)), Fraction(m.group(3)), m.group(4).split(),
                             int(m.group(5))))
    return rows


def primes(lo, hi):
    return [n for n in range(lo, hi + 1) if n > 1 and all(n % d for d in range(2, int(n ** 0.5) + 1))]


def main():
    cells_out, out_lean = sys.argv[1], sys.argv[2]
    count = int(sys.argv[3]) if len(sys.argv) > 3 else 80
    fs = farey(16)
    assert len(fs) == 81, len(fs)
    assert [Fraction(p, q) for p, q in fs] == breakpoints(), "breakpoints differ from Farey(16)"
    cells = [(p, q, p2, q2) for (p, q), (p2, q2) in zip(fs, fs[1:])]
    for p, q, p2, q2 in cells:
        assert p2 * q - p * q2 == 1
    qp = q_pairs()
    rows = parse_cells_out(cells_out)
    assert len(rows) == 80
    data = []
    for idx, cell in enumerate(cells):
        p, q, p2, q2 = cell
        theta = Fraction(p + p2, q + q2)
        order = entries_at(theta)
        comps = components(qp, ctx_pairs(order))
        z = next(c for c in comps if 0 in c)
        r = rows[idx]
        assert r[0] == idx and r[1] == Fraction(p, q) and r[2] == Fraction(p2, q2), (idx, r)
        ostr = [("+" if plus else "-") + str(A[i]) for i, plus, _ in order]
        assert ostr == r[3], (idx, ostr, r[3])
        assert len(comps) == r[4], (idx, len(comps), r[4])
        assert len(comps) >= 2
        assert lean_check(cell, order, z, qp), idx
        data.append((cell, order, z, len(comps)))
    nchk = 0
    for n in primes(17, PRIME_MAX):
        for mu in range(1, n):
            hit = [d for d in data if d[0][0] * n < d[0][1] * mu and d[0][3] * mu < d[0][2] * n]
            assert len(hit) == 1, (n, mu)
            (cell, order, _, _) = hit[0]
            levels = []
            for i, plus, k in order:
                r = mu * A[i] % n
                assert mu * A[i] // n == k
                assert (2 * r < n) == plus
                levels.append(r if plus else n - r)
            assert levels == sorted(levels) and len(set(levels)) == J and 0 < levels[0] and 2 * levels[-1] < n
            nchk += 1
    print(f"farey points={len(fs)} cells={len(cells)} cells.out rows matched={len(rows)} "
          f"cycles range=[{min(d[3] for d in data)},{max(d[3] for d in data)}] prime checks={nchk} "
          f"(primes 17..{PRIME_MAX})", file=sys.stderr)
    write_lean(out_lean, data[:count], qp)
    if len(sys.argv) > 5:
        write_checks(sys.argv[4], sys.argv[5], count)


def write_lean(path, data, qp):
    lines = [
        "import Repair.FactorCap.Checker",
        "",
        "/-!",
        "# Generated cell data for the factor-tail cap",
        "",
        "Generated by `gen_cells.py`. Do not edit. Each cell lies between Farey neighbours",
        "`p/q < p'/q'` of order 16 and lists the eight configuration entries in increasing level",
        "order as `⟨index, side, floor⟩`, then the closed end set `Z`.",
        "-/",
        "",
        "namespace Pairing",
        "",
        "namespace FactorCap",
        "",
    ]
    names = []
    for idx, (cell, order, z, ncyc) in enumerate(data):
        p, q, p2, q2 = cell
        ents = [f"⟨{i}, {'true' if plus else 'false'}, {k}⟩" for i, plus, k in order]
        zs = ", ".join(str(x) for x in z)
        name = f"cell{idx}"
        names.append(name)
        lines.append(f"/-- Cell {idx}, `θ ∈ ({p}/{q}, {p2}/{q2})`, {ncyc} cycles of `Q ∪ ∂`. -/")
        lines.append(f"def {name} : Cell :=")
        lines.append(f"  ⟨{p}, {q}, {p2}, {q2},")
        lines.append("    [" + ", ".join(ents[:4]) + ",")
        lines.append("      " + ", ".join(ents[4:]) + "],")
        lines.append(f"    [{zs}]⟩")
        lines.append("")
    lines.append("/-- The generated cells in increasing order of `θ`. -/")
    lines.append("def cells : List Cell :=")
    rows = [", ".join(names[i:i + 10]) for i in range(0, len(names), 10)]
    for r, row in enumerate(rows):
        lead = "  [" if r == 0 else "    "
        tail = "]" if r == len(rows) - 1 else ","
        lines.append(lead + row + tail)
    lines.append("")
    lines.append("end FactorCap")
    lines.append("")
    lines.append("end Pairing")
    lines.append("")
    with open(path, "w") as fh:
        fh.write("\n".join(lines))


def write_checks(path, module, count):
    lines = [
        "import Repair.FactorCap.CellData",
        "",
        "/-!",
        f"# {module}: kernel checks of the first {count} factor-cap cells",
        "",
        "Generated by `gen_cells.py`. Do not edit. Each cell is checked by `decide +kernel` in its",
        "own theorem.",
        "-/",
        "",
        "namespace Pairing",
        "",
        "namespace FactorCap",
        "",
    ]
    for i in range(count):
        lines.append(f"/-- Cell {i} passes the checker. -/")
        lines.append(f"theorem cell{i}_check : cell{i}.check = true := by decide +kernel")
        lines.append("")
    if count == 80:
        names = [f"cell{i}_check" for i in range(count)]
        lines.append("/-- All 80 cells pass the checker, assembled from the per-cell kernel checks. -/")
        lines.append("theorem cells_check_of_lemmas : cells.all Cell.check = true := by")
        lines.append("  simp only [cells, List.all_cons, List.all_nil, Bool.and_true,")
        rows = [", ".join(names[i:i + 5]) for i in range(0, count, 5)]
        for r, row in enumerate(rows):
            lines.append("    " + row + ("]" if r == len(rows) - 1 else ","))
        lines.append("")
    lines.append("end FactorCap")
    lines.append("")
    lines.append("end Pairing")
    lines.append("")
    with open(path, "w") as fh:
        fh.write("\n".join(lines))


if __name__ == "__main__":
    main()
